const VOCAB = [...new Set(RECIPES.flatMap((r) => [...r.need.flat(), ...r.opt]))];
const norm = (s) => String(s || '').replace(/\s/g, '');

/** 냉장고 한 줄 이름이 가리키는 재료 낱말 — 「양배추」는 배추가 아니고, 「닭가슴살」은 닭이 아니다(긴 낱말이 이긴다) */
export function ingredientWords(name) {
  const n = norm(name);
  const hit = VOCAB.filter((w) => n.includes(w));
  return hit.filter((w) => !hit.some((o) => o !== w && o.includes(w)));
}

/**
 * 냉장고 → 추천 목록. items: [{name, left}] (left = 남은 날, 작을수록 급함)
 * 꼭 있어야 할 재료가 2개 이상 빠지면 빼고, 급한 재료를 쓰는 요리를 앞에.
 */
export function suggestRecipes(items, limit = 6) {
  const have = new Map(); // 재료 낱말 → 가장 급한 남은 날
  for (const it of items) for (const w of ingredientWords(it.name)) {
    const left = it.left ?? 99;
    if (!have.has(w) || left < have.get(w)) have.set(w, left);
  }
  const out = [];
  for (const r of RECIPES) {
    const got = [], missing = [];
    for (const alts of r.need) { const w = alts.find((a) => have.has(a)); if (w) got.push(w); else missing.push(alts[0]); }
    if (!got.length || missing.length > 1) continue;
    const extras = r.opt.filter((o) => have.has(o) && !got.includes(o));
    const used = [...got, ...extras];
    const urgent = used.filter((w) => have.get(w) <= 2);
    // 다 갖춘 요리 > 급한 재료를 쓰는 요리 > 냉장고를 더 많이 비우는 요리
    const score = (got.length / r.need.length) * 100 + urgent.length * 30 + used.length * 8 - missing.length * 40;
    out.push({ ...r, got, extras, missing, urgent, score });
  }
  return out.sort((a, b) => b.score - a.score || a.min - b.min).slice(0, limit);
}

/** AI 에게 물을 글 (열쇠가 있을 때 비서 화면에 미리 넣어 줌 — 보내기는 사용자가) */
export function recipeQuestion(items) {
  const list = items.slice().sort((a, b) => (a.left ?? 99) - (b.left ?? 99)).slice(0, 12)
    .map((x) => `${x.name}${x.left != null && x.left <= 2 ? '(급함)' : ''}`).join(', ');
  return `냉장고에 있는 재료: ${list}. 급한 재료부터 쓰는 오늘 저녁 메뉴 2가지와 간단한 만드는 법을 알려 줘.`;
}
